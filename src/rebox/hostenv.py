"""Reproducing the conda environment rebox runs in, for offline bundles.

rebox is installed as a conda package, globally (`pixi global install rebox`)
or in any Pixi environment. `rebox pack` ships exactly that environment: the
packages recorded in ``<prefix>/conda-meta`` are pinned (version, build and
channel) in a temporary Pixi manifest, locked with ``pixi lock`` and packed
with ``pixi-pack``.
"""

from __future__ import annotations

import json
import platform
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

import tomli_w

from .config import ConfigError

PLATFORMS = {"x86_64": "linux-64", "aarch64": "linux-aarch64", "ppc64le": "linux-ppc64le"}


@dataclass(frozen=True)
class Installed:
    name: str
    version: str
    build: str
    channel: str
    subdir: str


def installed_packages(prefix: Path | None = None) -> list[Installed]:
    meta = (prefix or Path(sys.prefix)) / "conda-meta"
    packages = []
    for record in sorted(meta.glob("*.json")):
        try:
            data = json.loads(record.read_text())
        except (OSError, json.JSONDecodeError):
            continue
        if not {"name", "version", "build"} <= set(data):
            continue
        channel = str(data.get("channel") or "").rstrip("/")
        url = str(data.get("url") or "")
        subdir = str(data.get("subdir") or "")
        if (not channel or "://" not in channel) and url and subdir and f"/{subdir}/" in url:
            channel = url.rsplit(f"/{subdir}/", 1)[0]
        if not channel:
            raise ConfigError(f"Cannot tell which channel {data['name']} was installed from ({record})")
        packages.append(Installed(data["name"], data["version"], data["build"], channel, subdir))
    return packages


def host_manifest(packages: list[Installed]) -> dict:
    """A Pixi manifest pinning exactly ``packages``."""
    if not any(p.name == "rebox" for p in packages):
        raise ConfigError(
            "`rebox pack` ships the conda environment rebox runs in, but rebox is not installed "
            f"as a conda package in {sys.prefix} (install it with `pixi global install rebox` "
            "or in a Pixi environment)"
        )
    subdirs = {p.subdir for p in packages if p.subdir and p.subdir != "noarch"}
    plat = next(iter(subdirs)) if len(subdirs) == 1 else PLATFORMS.get(platform.machine(), "linux-64")
    channels = list(dict.fromkeys(p.channel for p in packages))
    # conda-forge last, so that it does not shadow the channel rebox comes from
    channels.sort(key=lambda c: c.rstrip("/").endswith("/conda-forge"))
    return {
        "workspace": {"name": "rebox-host", "channels": channels, "platforms": [plat]},
        "dependencies": {
            p.name: {"version": f"=={p.version}", "build": p.build, "channel": p.channel}
            for p in packages
        },
    }


def pack_host_environment(output: Path, workdir: Path) -> None:
    """Write a self-extracting copy of the running conda environment to ``output``."""
    pixi = shutil.which("pixi")
    pixi_pack = shutil.which("pixi-pack")
    if not pixi:
        raise ConfigError("pixi not found on PATH (needed to lock the host environment)")
    if not pixi_pack:
        raise ConfigError("pixi-pack not found (it is a dependency of the rebox package)")
    manifest = host_manifest(installed_packages())
    workdir.mkdir(parents=True, exist_ok=True)
    (workdir / "pixi.toml").write_text(
        "# Exact copy of the conda environment rebox ran in (generated by rebox pack).\n"
        + tomli_w.dumps(manifest)
    )
    print(f"Locking the host environment ({len(manifest['dependencies'])} packages)...", flush=True)
    subprocess.run([pixi, "lock", "--manifest-path", str(workdir / "pixi.toml")], check=True)
    print("Packing the host environment with pixi-pack...", flush=True)
    subprocess.run([pixi_pack, str(workdir / "pixi.toml"), "--create-executable",
                    "--output-file", str(output)], check=True)
