"""Exporting a reproducible specification and packing offline bundles."""

from __future__ import annotations

import datetime as dt
import hashlib
import shutil
import stat
import subprocess
import tarfile
import tempfile
from pathlib import Path
from typing import Any

import tomli_w

from . import __version__
from .build import render_def
from .config import ConfigError, SandboxEnv
from .run import apptainer_bin

PACKAGE_DIR = Path(__file__).resolve().parent

DEFAULTS_PLACEHOLDER = """\
# This project was exported by rebox. Every exported environment is
# fully resolved (inherit_defaults = false), so no defaults are needed here.
# Add [build] / [resources] tables to define defaults for new environments.
"""

INSTALL_SH = """\
#!/bin/sh
# Install the host tools (Python, Apptainer...) of this offline bundle.
# No network access is needed.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
cd "$HERE"
if [ ! -f "$HERE/.host/activate.sh" ]; then
    ./host-env.sh --output-directory "$HERE/.host" --env-name env --quiet
fi
echo "Installed. Use ./rebox to manage environments, e.g.: ./rebox shell {name}"
"""

WRAPPER_SH = """\
#!/bin/sh
# Run rebox with the host tools unpacked by install.sh.
HERE=$(cd "$(dirname "$0")" && pwd)
if [ ! -f "$HERE/.host/activate.sh" ]; then
    echo "Run $HERE/install.sh first." >&2
    exit 1
fi
. "$HERE/.host/activate.sh"
export REBOX_ROOT="$HERE"
export PYTHONPATH="$HERE/src${PYTHONPATH:+:$PYTHONPATH}"
exec python -m rebox "$@"
"""


def file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def apptainer_version() -> str:
    try:
        out = subprocess.run([apptainer_bin(), "version"], capture_output=True, text=True, check=True)
        return out.stdout.strip()
    except (ConfigError, subprocess.CalledProcessError, OSError):
        return "unknown"


def resolved_sandbox_toml(env: SandboxEnv) -> dict[str, Any]:
    """A sandbox.toml equivalent to ``env`` that does not depend on defaults.toml.

    Every recipe is pinned to its exact version and read from a local copy of
    its source (``recipes/<source>/``), so no git access is needed.
    """
    used_sources = list(dict.fromkeys(r.source for r in env.recipes))
    return {
        "description": env.description,
        "inherit_defaults": False,
        "sources": {name: {"path": f"recipes/{name}"} for name in used_sources},
        "build": {
            "base_image": env.base_image,
            "default_recipes": [],
            "recipes": [f"{r.source}:{r.name}@=={r.version}" for r in env.recipes],
            "recipe_args": {name: args for name, args in env.recipe_args.items() if args},
        },
        "resources": dict(env.raw.get("resources", {})),
    }


def lock_data(env: SandboxEnv) -> dict[str, Any]:
    from .recipes import lock_entries

    data: dict[str, Any] = {
        "lock_version": 2,
        "generated": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "tool_version": __version__,
        "apptainer_version": apptainer_version(),
        "environment": env.name,
        "base_image": env.base_image,
        "definition_sha256": hashlib.sha256(render_def(env).encode()).hexdigest(),
    }
    if env.image.is_file():
        data["image_sha256"] = file_sha256(env.image)
    lock = env.workspace / "pixi.lock"
    if lock.is_file():
        data["workspace_pixi_lock_sha256"] = file_sha256(lock)
    data["recipes"] = lock_entries(env.recipes, env.sources, env.recipe_args)
    return data


LOCK_HEADER = """\
# Resolved recipe versions of this environment (and build information).
# Builds reuse these exact versions; change them with `rebox update`.
# Generated by rebox: do not edit by hand.
"""


def write_lock(env: SandboxEnv) -> Path:
    env.lock_file.write_text(LOCK_HEADER + tomli_w.dumps(lock_data(env)))
    return env.lock_file


def _relock(out: Path, name: str) -> None:
    from .config import Project, load_env
    write_lock(load_env(Project(out), name, check_binds=False))


def export_env(env: SandboxEnv, out: Path) -> Path:
    """Write a standalone project directory that rebuilds ``env`` identically."""
    if out.exists() and any(out.iterdir()):
        raise ConfigError(f"Output directory {out} is not empty")
    out.mkdir(parents=True, exist_ok=True)
    root = env.project.root

    # Host tooling
    for name in ("pixi.toml", "pixi.lock", "README.md"):
        if (root / name).is_file():
            shutil.copy2(root / name, out / name)
    shutil.copytree(PACKAGE_DIR, out / "src" / "rebox", ignore=shutil.ignore_patterns("__pycache__"))
    (out / "defaults.toml").write_text(DEFAULTS_PLACEHOLDER)

    # Exact versions of the recipes used, one local source per original source
    for recipe in env.recipes:
        target = out / "recipes" / recipe.source / recipe.name / f"{recipe.version}.toml"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(recipe.text)
    for source in dict.fromkeys(r.source for r in env.recipes):
        (out / "recipes" / source / "source.toml").write_text(
            f'description = "Recipes exported from source \'{source}\' ({env.sources[source].describe()})"\n'
        )

    # Environment
    env_out = out / "envs" / env.name
    (env_out / "workspace").mkdir(parents=True)
    (env_out / "sandbox.toml").write_text(
        f"# Resolved export of environment '{env.name}' (defaults merged in).\n"
        + tomli_w.dumps(resolved_sandbox_toml(env))
    )
    for name in ("pixi.toml", "pixi.lock"):
        if (env.workspace / name).is_file():
            shutil.copy2(env.workspace / name, env_out / "workspace" / name)
    (env_out / "build.def").write_text(render_def(env))
    _relock(out, env.name)
    return out


def _make_executable(path: Path) -> None:
    path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def pack_env(env: SandboxEnv, output: Path, *, include_home: bool = False) -> Path:
    """Create a tarball that redeploys ``env`` on a machine without internet."""
    if not env.image.is_file():
        raise ConfigError(f"Image not built yet: run `rebox build {env.name}` first")
    pixi_pack = shutil.which("pixi-pack")
    if not pixi_pack:
        raise ConfigError("pixi-pack not found on PATH (it is a dependency of the host Pixi environment)")
    root = env.project.root
    if not (root / "pixi.lock").is_file():
        raise ConfigError("The project has no pixi.lock; run `pixi install` first")

    bundle_name = output.name.removesuffix(".tar").removesuffix(".tar.gz")
    with tempfile.TemporaryDirectory(prefix="sandbox-pack-") as tmp:
        stage = Path(tmp) / bundle_name
        export_env(env, stage)
        env_out = stage / "envs" / env.name

        # Built image and installed workspace (including .pixi, valid at /sandbox)
        state = env_out / ".state"
        state.mkdir()
        shutil.copy2(env.image, state / "image.sif")
        shutil.copy2(env.def_file if env.def_file.is_file() else env_out / "build.def", state / "build.def")
        shutil.rmtree(env_out / "workspace")
        shutil.copytree(env.workspace, env_out / "workspace", symlinks=True)
        if include_home and env.home_dir.is_dir():
            shutil.copytree(env.home_dir, state / "home", symlinks=True)
        _relock(stage, env.name)  # now records the image checksum too

        # Host tools as a self-extracting conda environment
        print("Packing host tools with pixi-pack...")
        subprocess.run(
            [pixi_pack, str(root / "pixi.toml"), "--create-executable",
             "--output-file", str(stage / "host-env.sh")],
            check=True,
        )
        _make_executable(stage / "host-env.sh")
        (stage / "install.sh").write_text(INSTALL_SH.format(name=env.name))
        (stage / "rebox").write_text(WRAPPER_SH)
        _make_executable(stage / "install.sh")
        _make_executable(stage / "rebox")

        output.parent.mkdir(parents=True, exist_ok=True)
        print(f"Writing {output}...")
        mode = "w:gz" if output.name.endswith(".gz") else "w"
        with tarfile.open(output, mode) as tar:
            tar.add(stage, arcname=bundle_name)
    return output
