"""Turning a resolved environment into an Apptainer image."""

from __future__ import annotations

import shlex
import shutil
import subprocess
from pathlib import Path

from .config import SANDBOX_HOME, WORKSPACE_TARGET, ConfigError, SandboxEnv
from .run import apptainer_bin, build_command, run_command

BOOTSTRAP_AGENTS = {
    "docker": "docker",
    "oras": "oras",
    "library": "library",
    "localimage": "localimage",
    "shub": "shub",
}


def parse_base_image(base_image: str) -> tuple[str, str]:
    """Split 'docker://debian:12' into ('docker', 'debian:12')."""
    if "://" not in base_image:
        raise ConfigError(
            f"base_image '{base_image}' needs a scheme, e.g. docker://debian:12-slim "
            "or localimage://path/to/base.sif"
        )
    scheme, ref = base_image.split("://", 1)
    if scheme not in BOOTSTRAP_AGENTS:
        raise ConfigError(f"Unsupported base_image scheme '{scheme}'")
    return BOOTSTRAP_AGENTS[scheme], ref


def render_def(env: SandboxEnv) -> str:
    """Render a self-contained Apptainer definition file.

    Recipe scripts are inlined so the .def file alone describes the image.
    """
    if not env.recipes:
        raise ConfigError(f"Environment '{env.name}' has no resolved recipe")
    agent, ref = parse_base_image(env.base_image)
    if agent == "localimage":
        local = Path(ref)
        if not local.is_absolute():
            local = (env.project.root / local).resolve()
        ref = str(local)

    lines = [
        f"# Generated by rebox for environment '{env.name}'.",
        "# Do not edit: regenerate with `rebox build " + env.name + "`.",
        f"Bootstrap: {agent}",
        f"From: {ref}",
        "",
        "%labels",
        f"    org.rebox.env {env.name}",
        f"    org.rebox.recipes {','.join(r.ref for r in env.recipes)}",
        "",
        "%environment",
        f"    export HOME={SANDBOX_HOME}",
        f"    export REBOX_NAME={shlex.quote(env.name)}",
        f"    export REBOX_WORKSPACE={WORKSPACE_TARGET}",
    ]
    for recipe in env.recipes:
        for key, value in recipe.environment.items():
            lines.append(f"    export {key}={_env_value(value)}")
    lines += ["", "%post", "    set -eu", f"    mkdir -p {WORKSPACE_TARGET} {SANDBOX_HOME}"]
    for recipe in env.recipes:
        lines += ["", f"    # ---- recipe: {recipe.ref} (sha256 {recipe.digest[:12]}) ----"]
        lines.append(f"    echo '==> [sandbox] recipe {recipe.name} {recipe.version} ({recipe.source})'")
        lines.append("    (")
        lines.append("    set -eu")
        for key, value in env.recipe_args[recipe.name].items():
            lines.append(f"    export {key}={shlex.quote(value)}")
        # Recipe lines are not indented so that heredocs keep working.
        lines += recipe.post.strip("\n").splitlines()
        lines.append("    )")
    lines.append("    chmod 1777 " + WORKSPACE_TARGET)
    runscripts = [r.runscript for r in env.recipes if r.runscript]
    if runscripts:
        lines += ["", "%runscript"] + [f"    {line}" for line in runscripts[-1].strip().splitlines()]
    return "\n".join(lines) + "\n"


def _env_value(value: str) -> str:
    # Allow $VAR references (e.g. PATH=/opt/x/bin:$PATH) but quote everything else.
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("`", "\\`") + '"'


def build_image(env: SandboxEnv, *, force: bool = False, dry_run: bool = False) -> Path:
    env.state_dir.mkdir(parents=True, exist_ok=True)
    definition = render_def(env)
    changed = not env.def_file.is_file() or env.def_file.read_text() != definition
    if not dry_run:
        env.def_file.write_text(definition)
    if env.image.is_file() and not changed and not force:
        print(f"Image is up to date: {env.image}")
        return env.image

    tmp_image = env.image.with_suffix(".sif.tmp")
    cmd = [apptainer_bin(), "build", "--fakeroot", "--force"]
    if not shutil.which("newuidmap"):
        # Without the setuid newuidmap helper, /etc/subuid entries cannot be used:
        # fall back to a root-mapped user namespace (no privileges needed).
        cmd.append("--ignore-subuid")
    cmd += [str(tmp_image), str(env.def_file)]
    print("$ " + shlex.join(cmd))
    if dry_run:
        print(definition)
        return env.image
    subprocess.run(cmd, check=True)
    tmp_image.replace(env.image)
    print(f"Built {env.image}")
    return env.image


def prepare_workspace(env: SandboxEnv, *, dry_run: bool = False) -> None:
    """Install the inner Pixi environment (with network) so it is ready offline."""
    manifest = env.workspace / "pixi.toml"
    if not manifest.is_file():
        print("No workspace/pixi.toml: skipping Pixi environment installation")
        return
    if not env.has_recipe("pixi"):
        print("Environment does not use the 'pixi' recipe: skipping workspace installation")
        return
    _reset_moved_workspace(env, dry_run=dry_run)
    cmd = build_command(
        env,
        ["pixi", "install", "--manifest-path", f"{WORKSPACE_TARGET}/pixi.toml"],
        network_override="host",
        limits=False,
    )
    code = run_command(env, cmd, dry_run=dry_run, keep_proxy=True)
    if code != 0:
        raise ConfigError(f"`pixi install` in the sandbox workspace failed (exit code {code})")
    if not dry_run:
        (env.workspace / ".pixi" / MOUNT_MARKER).write_text(WORKSPACE_TARGET + "\n")


MOUNT_MARKER = "rebox-mount-point"


def _reset_moved_workspace(env: SandboxEnv, *, dry_run: bool = False) -> None:
    """Remove Pixi environments installed for another mount point.

    Conda prefixes embed their absolute path: environments installed when the
    workspace was mounted elsewhere (``/sandbox`` before rebox 0.4) must be
    reinstalled.
    """
    envs = env.workspace / ".pixi" / "envs"
    if not envs.is_dir():
        return
    marker = env.workspace / ".pixi" / MOUNT_MARKER
    mounted_at = marker.read_text().strip() if marker.is_file() else None
    if mounted_at == WORKSPACE_TARGET:
        return
    print(f"Reinstalling the workspace Pixi environments for the {WORKSPACE_TARGET} mount point")
    if not dry_run:
        shutil.rmtree(envs)


def clean(env: SandboxEnv, *, all_state: bool = False) -> None:
    targets = [env.state_dir] if all_state else [env.image, env.def_file]
    for target in targets:
        if target.is_dir():
            shutil.rmtree(target)
            print(f"Removed {target}")
        elif target.exists():
            target.unlink()
            print(f"Removed {target}")
